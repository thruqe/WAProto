// IsScalarType returns whether the given type name is a protobuf scalar.
func IsScalarType(t string) bool {
	return scalarTypes[strings.ToLower(strings.TrimSpace(t))]
}

// LookupPackageForType finds the target modular package for a given type name.
func LookupPackageForType(typeName string) string {
	typeName = strings.TrimSpace(typeName)
	if pkg, ok := TypeToPackage[typeName]; ok {
		return pkg
	}
	for _, p := range Packages {
		if p.Package == typeName || p.Dir == typeName {
			return p.Dir
		}
	}
	return "waE2E"
}
